  const difficultySettings = {
    easy: { enemyHp: .7, damage: .6, playerHp: 150 },
    medium: { enemyHp: 1, damage: 1, playerHp: 110 },
    hard: { enemyHp: 1.35, damage: 1.5, playerHp: 100 },
    extreme: { enemyHp: 1.8, damage: 2.1, playerHp: 90 }
  };

  // ---------------- GAME STATE ----------------

  let chapter = 0;
  let player;
  let enemies = [];
  let projectiles = [];
  let effects = [];
  let keys = Object.create(null);

  let started = false;
  let gameOver = false;
  let victory = false;
  let chapterCleared = false;
  let transitionLocked = false;
  let takeoverComplete = false;
  let cutscene = null;

  let message = "";
  let messageTimer = 0;
  let elapsed = 0;
  let shake = 0;
  let lastTime = 0;
  let frameId = 0;

  let settings = difficultySettings.medium;

  const W = canvas.width;
  const H = canvas.height;
  const rand = (a, b) => a + Math.random() * (b - a);
  const clamp = (v, a, b) => Math.max(a, Math.min(b, v));

  function makePlayer() {
    return {
      x: 100, y: 350, w: 28, h: 40,
      hp: settings.playerHp,
      maxHp: settings.playerHp,
      speed: 190,
      facing: 1,
      moving: false,
      anim: 0,
      swordCd: 0,
      skillCd: 0,
      divergentCd: 0,
      flameCd: 0,
      invulnerable: 0
    };
  }

  function say(text, duration = 2.5) {
    message = text;
    messageTimer = duration;
  }

  // ---------------- EFFECTS ----------------

  function particles(x, y, color, count = 14, power = 100) {
    for (let i = 0; i < count; i++) {
      const angle = rand(0, Math.PI * 2);
      const speed = rand(power * .2, power);
      effects.push({
        type: "particle",
        x, y,
        vx: Math.cos(angle) * speed,
        vy: Math.sin(angle) * speed,
        life: rand(.25, .8),
        maxLife: .8,
        color,
        size: rand(2, 6)
      });
    }
  }

  function slashEffect(x, y, color, count = 5, facing = 1) {
    for (let i = 0; i < count; i++) {
      effects.push({
        type: "slash",
        x: x + facing * rand(-10, 20),
        y: y + rand(-23, 23),
        vx: facing * rand(100, 250),
        vy: rand(-150, 150),
        life: rand(.16, .35),
        maxLife: .35,
        color,
        size: rand(18, 48)
      });
    }
  }

  function explosion(x, y, color, radius, life = .45) {
    effects.push({
      type: "explosion", x, y, color, radius,
      life, maxLife: life
    });
  }

  function updateEffects(dt) {
    for (const e of effects) {
      e.life -= dt;
      if (e.type !== "explosion") {
        e.x += e.vx * dt;
        e.y += e.vy * dt;
        e.vy += 50 * dt;
      }
    }
    effects = effects.filter(e => e.life > 0);
    shake = Math.max(0, shake - dt * 18);
  }

  function drawEffects() {
    for (const e of effects) {
      const alpha = clamp(e.life / e.maxLife, 0, 1);
      ctx.save();
      ctx.globalAlpha = alpha;

      if (e.type === "particle") {
        ctx.fillStyle = e.color;
        ctx.fillRect(e.x, e.y, e.size, e.size);
      } else if (e.type === "slash") {
        ctx.strokeStyle = e.color;
        ctx.lineWidth = 3;
        ctx.beginPath();
        ctx.moveTo(e.x, e.y);
        ctx.lineTo(e.x - e.size, e.y - e.size * .4);
        ctx.stroke();
      } else {
        const r = e.radius * (1 - alpha);
        ctx.strokeStyle = e.color;
        ctx.lineWidth = 4 + alpha * 4;
        ctx.beginPath();
        ctx.arc(e.x, e.y, r, 0, Math.PI * 2);
        ctx.stroke();

        ctx.globalAlpha = alpha * .2;
        ctx.fillStyle = e.color;
        ctx.beginPath();
        ctx.arc(e.x, e.y, r, 0, Math.PI * 2);
        ctx.fill();
      }

      ctx.restore();
    }
  }

  // ---------------- ENEMIES ----------------

  function makeEnemy(type, x, y, hp, size = 28) {
    return {
      type, x, y, w: size, h: size,
      hp, maxHp: hp,
      speed: rand(28, 55),
      damage: 8 * settings.damage,
      attackTimer: rand(.6, 1.6),
      flash: 0,
      phase: rand(0, 6),
      vx: 0
    };
  }

  function spawnEnemies() {
    enemies = [];
    projectiles = [];
    effects = [];

    const data = chapters[chapter];

    if (data.type === "boss") {
      const king = makeEnemy(
        "boss", 700, 300, 550 * settings.enemyHp, 82
      );
      king.h = 92;
      king.speed = 40;
      king.damage = 17 * settings.damage;
      enemies.push(king);
    } else {
      for (let i = 0; i < data.enemies; i++) {
        let hp = rand(30, 45) * settings.enemyHp;
        if (data.type === "knight" || data.type === "spirit") hp *= 1.35;
        enemies.push(makeEnemy(
          data.type, rand(340, 870), rand(300, 430), hp,
          data.type === "knight" ? 34 : 28
        ));
      }
    }
  }

  function aliveEnemies() {
    return enemies.filter(e => e.hp > 0);
  }

  // ---------------- STATUS AND PROGRESSION ----------------

  function refreshUI() {
    chapterText.textContent =
      `Chapter ${chapter + 1}/8 — ${chapters[chapter].name}`;

    if (takeoverComplete) {
      skillLabel.textContent = "M — Black Flash";
      skillLabel.style.borderColor = "#e52a48";
      skillLabel.style.color = "#ff536b";
      divergentLabel.textContent = "N — Divergent Fist";
      divergentLabel.style.opacity = "1";
      divergentLabel.style.borderColor = "#349dff";
      divergentLabel.style.color = "#73caff";
    } else {
      skillLabel.textContent = "M — Water Wheel";
      skillLabel.style.borderColor = "#409cd6";
      skillLabel.style.color = "#74d7ff";
      divergentLabel.textContent = "N — Locked until Chapter 6";
      divergentLabel.style.opacity = ".45";
      divergentLabel.style.borderColor = "#555";
      divergentLabel.style.color = "#aaa";
    }

    if (gameOver) {
      statusText.textContent = "You have fallen. Press Restart Game.";
    } else if (victory) {
      statusText.textContent = "The Purple King is defeated. You won!";
    } else if (cutscene) {
      statusText.textContent = "The Black Spirit is taking over...";
    } else if (chapterCleared) {
      statusText.textContent = "Chapter cleared! Continue when ready.";
    } else {
      statusText.textContent =
        `${chapters[chapter].description} Enemies remaining: ${aliveEnemies().length}`;
    }
  }

  function resetGame() {
    chapter = 0;
    started = false;
    gameOver = false;
    victory = false;
    chapterCleared = false;
    transitionLocked = false;
    takeoverComplete = false;
    cutscene = null;
    elapsed = 0;
    shake = 0;
    message = "";
    messageTimer = 0;
    settings = difficultySettings[difficultySelect.value] || difficultySettings.medium;

    player = makePlayer();
    spawnEnemies();

    difficultySelect.disabled = false;
    startButton.textContent = "Start Adventure";

    // The original welcome box can otherwise sit over the game.
    if ($("messageBox")) $("messageBox").style.display = "none";

    refreshUI();
  }

  function beginChapter() {
    if (gameOver || victory || cutscene || transitionLocked) return;

    // This lock prevents rapid/double clicks from advancing twice.
    transitionLocked = true;

    if (chapterCleared) {
      if (chapter === chapters.length - 1) {
        victory = true;
        started = false;
        say("THE PURPLE KING HAS FALLEN!", 8);
        refreshUI();
        transitionLocked = false;
        return;
      }

      chapter++;
      chapterCleared = false;
      player.x = 100;
      player.y = 350;
      player.hp = Math.min(player.maxHp, player.hp + 25);
      player.invulnerable = 1.5;
      spawnEnemies();
    }

    started = true;
    difficultySelect.disabled = true;
    startButton.textContent = "Continue to Next Chapter";

    if (chapter === 5 && !takeoverComplete) {
      beginTakeover();
    } else {
      say(chapters[chapter].description, 3);
    }

    transitionLocked = false;
    refreshUI();
  }

  function checkChapterClear() {
    if (chapterCleared || gameOver || victory || cutscene) return;
    if (aliveEnemies().length !== 0) return;

    chapterCleared = true;
    started = false;
    startButton.textContent =
      chapter === 7 ? "Finish Game" : "Continue to Next Chapter";
    say("All enemies defeated!", 3);
    refreshUI();
  }

  // ---------------- TAKEOVER CUTSCENE ----------------

  function beginTakeover() {
    started = false;
    cutscene = { time: 0, duration: 8 };
    say("The Black Spirit is awakening...", 8);
    shake = 4;
    refreshUI();
  }

  function finishTakeover() {
    // This function is called once, only at the end of the cutscene.
    if (!cutscene || takeoverComplete) return;

    cutscene = null;
    takeoverComplete = true;
    started = true;
    player.hp = player.maxHp;
    player.invulnerable = 2;

    particles(player.x + 14, player.y + 20, "#ff2347", 45, 180);
    particles(player.x + 14, player.y + 20, "#100d17", 40, 130);
    explosion(player.x + 14, player.y + 20, "#d51c40", 125, .6);
    shake = 12;

    say("BLACK DRAGON ARMOR AWAKENED!", 4);
    refreshUI();
  }

  function updateCutscene(dt) {
    if (!cutscene) return;

    cutscene.time += dt;

    if (Math.random() < .35) {
      particles(
        player.x + rand(-15, 35),
        player.y + rand(-5, 40),
        Math.random() < .5 ? "#17121e" : "#b91c3b",
        1, 55
      );
    }

    if (cutscene.time > 3 && cutscene.time < 7) {
      shake = Math.max(shake, 1.4);
    }

    if (cutscene.time >= cutscene.duration) finishTakeover();
  }

  // ---------------- COMBAT ----------------

  function damageEnemy(e, damage, knockback = 0) {
    if (!e || e.hp <= 0 || gameOver || victory) return;

    e.hp = Math.max(0, e.hp - damage);
    e.flash = .12;
    e.vx = knockback;

    if (e.hp === 0) {
      particles(
        e.x + e.w / 2, e.y + e.h / 2,
        e.type === "boss" ? "#bb55ff" : "#e34b64",
        e.type === "boss" ? 60 : 16,
        e.type === "boss" ? 180 : 100
      );
    }

    if (e.type === "boss" && e.hp <= 0) {
      victory = true;
      started = false;
      chapterCleared = false;
      say("THE PURPLE KING HAS FALLEN!", 8);
    }

    checkChapterClear();
    refreshUI();
  }

  function canAttack() {
    return started && !gameOver && !victory &&
      !chapterCleared && !cutscene;
  }

  function swordAttack() {
    if (!canAttack() || player.swordCd > 0) return;

    player.swordCd = .36;

    const x = player.x + player.w / 2 + player.facing * 25;
    const y = player.y + player.h / 2;
    slashEffect(x, y, takeoverComplete ? "#e92342" : "#edf4ff", 4, player.facing);

    for (const e of aliveEnemies()) {
      const dx = e.x + e.w / 2 - x;
      const dy = e.y + e.h / 2 - y;

      if (Math.abs(dx) < 63 && Math.abs(dy) < 46 &&
          Math.sign(dx || player.facing) === player.facing) {
        damageEnemy(e, 16, player.facing * 100);
      }
    }
  }

  // M before takeover ONLY.
  function waterWheel() {
    if (!canAttack() || takeoverComplete || player.skillCd > 0) return;

    player.skillCd = 2.2;
    const x = player.x + player.w / 2 + player.facing * 28;
    const y = player.y + player.h / 2;

    explosion(x, y, "#39baff", 88, .45);
    slashEffect(x, y, "#77eaff", 12, player.facing);
    particles(x, y, "#46caff", 18, 120);
    shake = 4;

    for (const e of aliveEnemies()) {
      if (Math.abs(e.x + e.w / 2 - x) < 100 &&
          Math.abs(e.y + e.h / 2 - y) < 72) {
        damageEnemy(e, 28, player.facing * 170);
      }
    }
  }

  // M after takeover ONLY.
  function blackFlash() {
    if (!canAttack() || !takeoverComplete || player.skillCd > 0) return;

    player.skillCd = 1.25;
    const x = player.x + player.w / 2 + player.facing * 35;
    const y = player.y + player.h / 2;

    player.x = clamp(player.x + player.facing * 30, 0, W - player.w);

    slashEffect(x, y, "#050508", 17, player.facing);
    slashEffect(x, y, "#ff163d", 14, player.facing);
    particles(x, y, "#ff2447", 20, 180);
    explosion(x, y, "#a50e31", 65, .3);
    shake = 7;

    for (const e of aliveEnemies()) {
      const dx = e.x + e.w / 2 - x;
      const dy = e.y + e.h / 2 - y;

      if (Math.abs(dx) < 110 && Math.abs(dy) < 70 &&
          Math.sign(dx || player.facing) === player.facing) {
        damageEnemy(e, 38, player.facing * 240);
      }
    }

    say("BLACK FLASH!", .7);
  }

  // N after takeover ONLY. There is no Water Wheel call here.
  function divergentFist() {
    if (!canAttack() || !takeoverComplete || player.divergentCd > 0) return;

    player.divergentCd = 3;
    const x = player.x + player.w / 2 + player.facing * 38;
    const y = player.y + player.h / 2;

    particles(x, y, "#46caff", 25, 130);
    explosion(x, y, "#46caff", 42, .25);
    say("DIVERGENT FIST!", .8);

    for (const e of aliveEnemies()) {
      if (Math.abs(e.x + e.w / 2 - x) < 82 &&
          Math.abs(e.y + e.h / 2 - y) < 58) {
        damageEnemy(e, 12, player.facing * 130);
      }
    }

    // A single delayed second impact, cancelled if the game resets.
    const currentChapter = chapter;
    const currentPlayer = player;

    window.setTimeout(() => {
      if (player !== currentPlayer || chapter !== currentChapter ||
          gameOver || victory) return;

      explosion(x + player.facing * 15, y, "#168bff", 125, .55);
      particles(x + player.facing * 15, y, "#6ee2ff", 38, 220);
      particles(x + player.facing * 15, y, "#187aff", 25, 160);
      shake = 8;

      for (const e of aliveEnemies()) {
        if (Math.abs(e.x + e.w / 2 - x) < 145 &&
            Math.abs(e.y + e.h / 2 - y) < 100) {
          damageEnemy(e, 28, player.facing * 220);
        }
      }
    }, 190);
  }

  function flameArrow() {
    if (!canAttack() || player.flameCd > 0) return;

    player.flameCd = 1.15;
    projectiles.push({
      x: player.x + player.w / 2 + player.facing * 15,
      y: player.y + 18,
      vx: player.facing * 360,
      vy: 0,
      life: 1.6,
      damage: 22,
      type: "flame"
    });

    particles(player.x + 14, player.y + 18, "#ff8137", 8, 70);
  }

  // ---------------- ENEMY AI ----------------

  function hurtPlayer(amount) {
    if (player.invulnerable > 0 || gameOver || cutscene) return;

    player.hp = Math.max(0, player.hp - amount);
    player.invulnerable = .75;
    shake = 4;

    if (player.hp <= 0) {
      gameOver = true;
      started = false;
      say("You have fallen into darkness.", 8);
    }

    refreshUI();
  }

  function enemyAttack(e) {
    const px = player.x + player.w / 2;
    const py = player.y + player.h / 2;
    const ex = e.x + e.w / 2;
    const ey = e.y + e.h / 2;

    if (e.type === "boss") {
      const choice = Math.random();

      if (choice < .4) {
        projectiles.push({
          x: ex, y: ey,
          vx: (px - ex) * .42,
          vy: (py - ey) * .42,
          life: 2.2,
          damage: 15 * settings.damage,
          type: "toxic",
          radius: 22
        });
        say("The Purple King releases toxic mist!", 1.2);
      } else if (choice < .72) {
        explosion(ex, ey, "#bd35ff", 150, .55);
        shake = 9;
        if (Math.abs(px - ex) < 180 && Math.abs(py - ey) < 115) {
          hurtPlayer(e.damage * 1.5);
        }
      } else {
        e.vx = Math.sign(px - ex) * 350;
        particles(ex, ey, "#8c2dca", 16, 120);
      }
      return;
    }

    if (Math.abs(px - ex) < 45 && Math.abs(py - ey) < 45) {
      hurtPlayer(e.damage);
    } else if (e.type === "spirit" && Math.random() < .5) {
      projectiles.push({
        x: ex, y: ey,
        vx: Math.sign(px - ex) * 145,
        vy: Math.sign(py - ey) * 50,
        life: 2,
        damage: e.damage,
        type: "shadow",
        radius: 8
      });
    }
  }

  function updateEnemies(dt) {
    for (const e of aliveEnemies()) {
      e.flash = Math.max(0, e.flash - dt);
      e.attackTimer -= dt;
      e.phase += dt;

      const dx = player.x + player.w / 2 - (e.x + e.w / 2);
      const dy = player.y + player.h / 2 - (e.y + e.h / 2);
      const dist = Math.hypot(dx, dy) || 1;

      if (e.type === "boss") {
        if (Math.abs(e.vx) > 10) {
          e.x += e.vx * dt;
          e.vx *= Math.pow(.04, dt);
        } else {
          e.vx = 0;
          if (dist > 125) {
            e.x += dx / dist * e.speed * dt;
            e.y += dy / dist * e.speed * dt;
          }
        }
        e.y += Math.sin(e.phase * 2) * 8 * dt;
      } else if (dist > 35) {
        e.x += dx / dist * e.speed * dt;
        e.y += dy / dist * e.speed * dt;
      }

      if (e.attackTimer <= 0) {
        enemyAttack(e);
        e.attackTimer = e.type === "boss" ? rand(1, 1.8) : rand(.8, 1.7);
      }

      e.x = clamp(e.x, 0, W - e.w);
      e.y = clamp(e.y, 275, H - e.h);
    }
  }

  function updateProjectiles(dt) {
    for (const p of projectiles) {
      p.x += p.vx * dt;
      p.y += p.vy * dt;
      p.life -= dt;

      if (p.type === "flame") {
        for (const e of aliveEnemies()) {
          if (Math.abs(e.x + e.w / 2 - p.x) < e.w / 2 + 10 &&
              Math.abs(e.y + e.h / 2 - p.y) < e.h / 2 + 10) {
            damageEnemy(e, p.damage, player.facing * 100);
            p.life = 0;
            particles(p.x, p.y, "#ff9b3c", 12, 90);
            break;
          }
        }
      } else {
        if (Math.hypot(
          player.x + player.w / 2 - p.x,
          player.y + player.h / 2 - p.y
        ) < (p.radius || 10) + 12) {
          hurtPlayer(p.damage);
          p.life = 0;
        }
      }
    }

    projectiles = projectiles.filter(p => p.life > 0);
  }

